#!/usr/bin/env bash
# Developer task runner for the robot firmware in the course project template.
#
#   bash scripts/dev.sh setup [setup options]     Pico SDK and ARM toolchain
#   bash scripts/dev.sh host-tests [pattern]      firmware/run_tests.sh (release + ASan/UBSan)
#   bash scripts/dev.sh style                     selected BARR-C lexical checks and
#                                                 the shared-write lock discipline
#   bash scripts/dev.sh app-tests [options]       application scenario tests
#   bash scripts/dev.sh integration               board IRQ, image gate, build script,
#                                                 radio and network fixtures
#   bash scripts/dev.sh build offline             uncommissioned offline image
#   bash scripts/dev.sh build mqtt                MQTT image with config/ network settings
#                                                 (in plain text in the ELF/UF2/map;
#                                                 share hashes only)
#   bash scripts/dev.sh build mqtt --compile-only MQTT image with labelled placeholder
#                                                 settings, built in a temporary copy
#   bash scripts/dev.sh all                       every check and both CI builds
#   bash scripts/dev.sh clean                     remove local build products
#
# Outputs go to $ROBOT_VALIDATION_DIR (default firmware/validation/local, which
# is git-ignored) and images to build-target/<profile>/ (git-ignored).
set -euo pipefail

log() { printf '[dev] %s\n' "$*"; }
die() { printf '[dev] ERROR: %s\n' "$*" >&2; exit 1; }

repo_root=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd -P)
firmware="$repo_root/firmware"
scripts="$firmware/scripts"

case "$(uname -s)" in
    MINGW*|MSYS*|CYGWIN*)
        printf 'Run this inside Ubuntu (WSL):  wsl.exe --cd "%s" -e bash scripts/dev.sh %s\n' "$repo_root" "$*"
        exit 2 ;;
esac

deps_dir="${ROBOT_DEPS_DIR:-$HOME/inf2004-deps}"
if [[ -f "$deps_dir/env.sh" ]]; then
    # shellcheck disable=SC1091
    source "$deps_dir/env.sh"
fi
sdk="${ROBOT_SDK:-$deps_dir/pico-sdk}"
out="${ROBOT_VALIDATION_DIR:-$firmware/validation/local}"
export ROBOT_VALIDATION_DIR="$out"
mkdir -p "$out"

need_deps() {
    [[ -d "$sdk/.git" ]] \
        || die "Pico SDK missing in $deps_dir; run: bash scripts/setup.sh (dev.sh reads only \$ROBOT_DEPS_DIR, default ~/inf2004-deps: after setup.sh --deps <dir>, export ROBOT_DEPS_DIR=<dir>)"
}

cmd_host_tests() {
    (cd "$firmware" && bash run_tests.sh "$@")
    # The laptop decoder shares the C encoder's golden telemetry vectors.
    (cd "$scripts" && python3 -m unittest -q test_telemetry_codec)
}
cmd_style() {
    python3 "$scripts/check_style.py" --report-dir "$out/style" "$@"
    python3 "$scripts/check_locks.py" --report "$out/style/lock-report.json"
}
cmd_app_tests() {
    python3 "$scripts/test_application.py" "$@"
}

cmd_integration() {
    need_deps
    log "board ISR fixtures with pinned SDK headers"
    python3 "$scripts/test_board_irq.py" --sdk "$sdk" --output "$out/board_irq"
    log "image structure gate fixtures"
    python3 "$scripts/test_inspect_target.py"
    log "build script failure-path fixtures"
    python3 "$scripts/test_build_target.py"
    log "radio startup with mocked driver/kernel"
    python3 "$scripts/test_radio_startup.py" --sdk "$sdk" --output "$out/radio-startup"
    log "MQTT adapter with real SDK types and mocked transport"
    python3 "$scripts/test_network_adapter.py" --sdk "$sdk" --output "$out/network"
    log "integration host checks passed; reports in $out"
}

# Labelled placeholders that cannot join any network, written into the
# config/ of a temporary project copy (never over real settings).
write_placeholders() {
    local config=$1
    python3 - "$config" <<'PY'
from pathlib import Path
import re, sys
config = Path(sys.argv[1])
wifi = (config / 'wifi_credentials.example.h').read_text()
wifi, count = re.subn(r'(#define\s+UTK_WIFI_CREDENTIALS_SET\s+)0', r'\g<1>1', wifi)
assert count == 1, 'unexpected wifi_credentials.example.h shape'
assert 'replace-with-ssid' in wifi and 'replace-with-password' in wifi
wifi = wifi.replace('replace-with-ssid', 'COMPILE-ONLY-NO-ACCESS-POINT')
wifi = wifi.replace('replace-with-password', 'COMPILE-ONLY-NO-CREDENTIAL')
(config / 'wifi_credentials.h').write_text(
    '/* COMPILE-ONLY PLACEHOLDER: generated by scripts/dev.sh; not a real network. */\n' + wifi)
mqtt = (config / 'net_mqtt_config.example.h').read_text()
old = '#define NET_MQTT_CONFIGURED 0'
assert mqtt.count(old) == 1
(config / 'net_mqtt_config.h').write_text(
    '/* COMPILE-ONLY PLACEHOLDER: broker 192.0.2.1 is a documentation address. */\n'
    + mqtt.replace(old, '#define NET_MQTT_CONFIGURED 1'))
PY
}

# Which hardware/course confirmation flags robot_config.h sets.
commissioning_label() {
    python3 - "$repo_root/app_program/robot_config.h" <<'PY'
import re, sys
text = open(sys.argv[1], encoding='utf-8').read()
flags = dict(re.findall(r'^#define\s+(ROBOT_\w+_CONFIRMED)\s+([01])\s*$', text, re.M))
confirmed = sorted(name for name, value in flags.items() if value == '1')
if not confirmed:
    print('Commissioning: UNCOMMISSIONED. All ROBOT_*_CONFIRMED flags are 0; '
          'the image refuses to start (ROBOT_WIRING_CONFIRMED=0).')
else:
    print('Commissioning: ' + ', '.join(confirmed) + ' set to 1; '
          + str(len(flags) - len(confirmed)) + ' flag(s) still 0.')
PY
}

cmd_build() {
    local profile=${1:-} mode=real project="$repo_root" scratch=""
    shift || true
    case "$profile" in offline|mqtt) ;; *) die "usage: build offline|mqtt [--compile-only]" ;; esac
    while [[ $# -gt 0 ]]; do
        case "$1" in
            --compile-only) mode=compile-only; shift ;;
            *) die "unknown build option: $1" ;;
        esac
    done
    need_deps
    command -v arm-none-eabi-gcc >/dev/null 2>&1 || die "arm-none-eabi-gcc not found; run: bash scripts/setup.sh"
    if [[ "$profile" == mqtt && "$mode" == compile-only ]]; then
        scratch=$(mktemp -d "${TMPDIR:-/tmp}/robot-compile-only.XXXXXX")
        # A RETURN trap stays set after this function returns, so it removes
        # itself: otherwise it would run again where $scratch is not defined.
        trap 'rm -rf -- "$scratch"; trap - RETURN' RETURN
        python3 - "$scripts" "$scratch/project" <<'PY'
import sys
sys.path.insert(0, sys.argv[1])
from pathlib import Path
from robot_paths import copy_project
copy_project(Path(sys.argv[2]))
PY
        project="$scratch/project"
        write_placeholders "$project/config"
        log "MQTT profile uses COMPILE-ONLY placeholder Wi-Fi/broker settings (temporary copy)"
    elif [[ "$profile" == mqtt ]]; then
        for name in wifi_credentials.h net_mqtt_config.h; do
            [[ -f "$repo_root/config/$name" ]] || die "missing config/$name; copy config/${name%.h}.example.h to config/$name and fill in real values (never commit them), or use --compile-only"
        done
        log "MQTT profile uses config/ network settings (not shown, not committed)"
        log "WARNING: the resulting ELF/UF2/map contain the Wi-Fi SSID/password and broker settings in plain text; never share or commit them, share hashes only"
    fi
    local evidence="$project/robot_build_evidence/$profile"
    local dest="$repo_root/build-target/$profile"
    local status=0
    bash "$scripts/build_target.sh" "$project" "$sdk" "$profile" || status=$?
    rm -rf -- "$dest"
    mkdir -p "$dest"
    cp -r -- "$evidence/." "$dest/"
    {
        printf 'Profile: %s\n' "$profile"
        printf 'Source revision: %s\n' "$(git -C "$repo_root" rev-parse HEAD 2>/dev/null || echo unknown)"
        if [[ -z "$(git -C "$repo_root" status --porcelain 2>/dev/null)" ]]; then
            printf 'Working tree: clean\n'
        else
            printf 'Working tree: has uncommitted changes\n'
        fi
        python3 - "$dest/toolchain.json" <<'PY'
import json, sys
try:
    data = json.load(open(sys.argv[1], encoding='utf-8'))
except (OSError, ValueError):
    print('Toolchain: not recorded (the build stopped before the toolchain check)')
    raise SystemExit(0)
version = data.get('arm-none-eabi-gcc', {}).get('version', 'unknown')
if data.get('toolchain_matches_pin'):
    print('Toolchain: %s (the pinned toolchain CI uses)' % version)
else:
    print('Toolchain: WARNING %s is not the pinned %s; image hashes are not '
          'comparable with CI' % (version, data.get('pinned_arm_toolchain', 'toolchain')))
PY
        commissioning_label
        if [[ "$profile" == mqtt && "$mode" == compile-only ]]; then
            printf 'MQTT settings: COMPILE-ONLY placeholders (no real SSID, credential or broker). Cannot connect.\n'
        elif [[ "$profile" == mqtt ]]; then
            printf 'MQTT settings: REAL settings from config/. The ELF, UF2 and map in this folder contain the Wi-Fi SSID/password and broker settings in plain text: never share, upload or commit them; share their SHA-256 hashes only.\n'
        fi
    } > "$dest/BUILD_LABEL.txt"
    if [[ $status -ne 0 ]]; then
        die "build failed (exit $status); see $dest/build.log and $dest/build-status.json"
    fi
    log "build passed; ELF/UF2/map and evidence in $dest"
    if [[ "$profile" == mqtt && "$mode" == real ]]; then
        log "WARNING: these images hold the config/ network settings in plain text; share hashes only (see BUILD_LABEL.txt)"
    fi
}

cmd_all() {
    cmd_host_tests
    cmd_style
    cmd_app_tests
    cmd_integration
    cmd_build offline
    cmd_build mqtt --compile-only
    log "all checks and builds completed"
}

cmd_clean() {
    if command -v make >/dev/null 2>&1; then
        make -C "$repo_root/build_make" clean >/dev/null 2>&1 || true
    fi
    rm -rf -- "$firmware/build-host" "$firmware/build-apphost" "$repo_root/build-target" \
        "$repo_root/robot_build_evidence" "$firmware/validation/local"
    log "local build products removed"
}

cmd=${1:-help}
shift || true
case "$cmd" in
    setup) exec bash "$repo_root/scripts/setup.sh" "$@" ;;
    host-tests) cmd_host_tests "$@" ;;
    style) cmd_style "$@" ;;
    app-tests) cmd_app_tests "$@" ;;
    integration) cmd_integration ;;
    build) cmd_build "$@" ;;
    all) cmd_all ;;
    clean) cmd_clean ;;
    help|-h|--help) sed -n '2,/^set -euo pipefail/p' "${BASH_SOURCE[0]}" | sed -n 's/^#//p' ;;
    *) die "unknown command: $cmd (try: bash scripts/dev.sh help)" ;;
esac
